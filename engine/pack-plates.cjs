#!/usr/bin/env node
'use strict';
const path = require('node:path');
const fs = require('node:fs/promises');
const sharp = require('sharp');

// Render-time SVG is self-contained in the web, Node, Remotion and offline HTML.
async function main() {
  const packed = {};
  for (const [code, source] of Object.entries({B:'basico', M:'medio', A:'avanzado', L:'managers'})) {
    const image = path.join(__dirname, 'plates', source+'.png');
    for (const [key, width, quality] of [[code, 1440, 84], [code+'-detail', 468, 70]]) {
      const bytes = await sharp(image).resize({width}).jpeg({quality, chromaSubsampling:'4:2:0'}).toBuffer();
      packed[key] = 'data:image/jpeg;base64,'+bytes.toString('base64');
    }
  }
  const contents = '/* Generated by pack-plates.cjs from plates/*.png. */\n'+
    '(function(root){const plates='+JSON.stringify(packed)+'; if(typeof module==="object"&&module.exports)module.exports=plates; else root.WorkshopPlates=plates;})(globalThis);\n';
  await fs.writeFile(path.join(__dirname,'plates.cjs'),contents);
}
main().catch(error => {console.error(error); process.exitCode=1;});
