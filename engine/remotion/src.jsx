import React, {useMemo} from 'react';
import {AbsoluteFill, Audio, Composition, registerRoot, staticFile, useCurrentFrame} from 'remotion';
import stage from '../stage.cjs';

function Lesson({episode,audioFile}) {
  const frame=useCurrentFrame();
  const prepared=useMemo(()=>stage.prepare(episode),[episode]);
  const faces=[['Open Sans',400,'OpenSans-Regular.ttf'],['Open Sans',600,'OpenSans-Semibold.ttf'],['Open Sans',700,'OpenSans-Bold.ttf'],['DejaVu Sans Mono',400,'DejaVuSansMono.ttf']];
  const css=faces.map(([name,weight,file])=>`@font-face{font-family:'${name}';font-weight:${weight};src:url('${staticFile('fonts/'+file)}') format('truetype')}`).join('');
  return <AbsoluteFill style={{background:'#102321'}}>
    <style>{css}</style>
    <div dangerouslySetInnerHTML={{__html:stage.frame(prepared,frame)}}/>
    {audioFile ? <Audio src={staticFile(audioFile)}/> : null}
  </AbsoluteFill>;
}

// Use --props generated by prepare.cjs when rendering a lesson. A small local
// composition is available in Studio even before a timed episode is selected.
const sample={id:'B00',title:'Studio preview',scenes:[{id:'preview',kind:'editor',
  title:'Prepare a lesson to preview',action:'Select a timed episode with prepare.cjs.',focus:'Inspect the frame and timing in Remotion Studio.',
  code:'node prepare.cjs --episode episode.json',result:'Open Studio with the generated props.',durationFrames:120}]};

function Root() {
  return <Composition id="Workshop" component={Lesson} width={1280} height={720} fps={24}
    durationInFrames={120} defaultProps={{episode:sample,audioFile:null}}
    calculateMetadata={({props})=>({durationInFrames:stage.prepare(props.episode).durationFrames})}/>;
}
registerRoot(Root);
